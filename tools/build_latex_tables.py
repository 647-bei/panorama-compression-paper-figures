"""Create downloadable LaTeX snippets for table assets.

PyMuPDF's table detector is used when the PDF contains recoverable table
structure.  Image-only or layout-heavy tables receive a transparent LaTeX
wrapper around the original high-resolution crop instead of invented cells.
"""
from __future__ import annotations

import json
import re
from pathlib import Path

import fitz


ROOT = Path(__file__).resolve().parents[1]


def latex_escape(value: object) -> str:
    text = str(value or "").replace("\u00a0", " ").replace("\n", " ")
    replacements = [
        ("\\", r"\textbackslash{}"),
        ("&", r"\&"),
        ("%", r"\%"),
        ("$", r"\$"),
        ("#", r"\#"),
        ("_", r"\_"),
        ("{", r"\{"),
        ("}", r"\}"),
        ("~", r"\textasciitilde{}"),
        ("^", r"\textasciicircum{}"),
    ]
    for old, new in replacements:
        text = text.replace(old, new)
    return re.sub(r"\s+", " ", text).strip()


def choose_table(page: fitz.Page, target_bbox: list[float] | None):
    finder = page.find_tables()
    tables = list(getattr(finder, "tables", []) or [])
    if not tables:
        return None
    if not target_bbox:
        return tables[0]
    target = fitz.Rect(target_bbox)

    def score(table):
        rect = fitz.Rect(table.bbox)
        intersection = rect & target
        overlap = intersection.get_area()
        center_distance = abs(rect.y0 - target.y0) + abs(rect.x0 - target.x0)
        return overlap, -center_distance

    return max(tables, key=score)


def normalize_rows(rows: list[list[object]]) -> list[list[str]]:
    clean: list[list[str]] = []
    for row in rows or []:
        values = [latex_escape(cell) for cell in (row or [])]
        if any(values):
            clean.append(values)
    if not clean:
        return []
    width = max(len(row) for row in clean)
    return [row + [""] * (width - len(row)) for row in clean]


def tabular_tex(caption: str, rows: list[list[str]]) -> str:
    columns = max(1, len(rows[0]))
    alignment = "l" * columns
    lines = [
        "% Auto-extracted table snippet; requires \\usepackage{booktabs}.",
        f"% Caption: {latex_escape(caption)}",
        f"\\begin{{tabular}}{{{alignment}}}",
        "\\toprule",
    ]
    for index, row in enumerate(rows):
        lines.append(" & ".join(row) + r" \\")
        if index == 0:
            lines.append("\\midrule")
    lines.extend(["\\bottomrule", "\\end{tabular}", ""])
    return "\n".join(lines)


def image_wrapper_tex(caption: str, original: Path) -> str:
    image_name = original.as_posix()
    return "\n".join(
        [
            "% Image wrapper: PDF table structure was not recoverable automatically.",
            "% Requires \\usepackage{graphicx}. Replace the image with tabular cells when editable text is needed.",
            f"% Caption: {latex_escape(caption)}",
            "\\begin{tabular}{c}",
            f"\\includegraphics[width=\\linewidth]{{{image_name}}}",
            "\\end{tabular}",
            "",
        ]
    )


def main() -> None:
    extracted = 0
    wrapped = 0
    for manifest_path in sorted(ROOT.glob("*/manifest.json")):
        data = json.loads(manifest_path.read_text(encoding="utf-8"))
        pdf_path = manifest_path.parent / data.get("pdf", "")
        table_assets = [asset for asset in data.get("assets", []) if asset.get("kind") == "table"]
        if not table_assets or not pdf_path.exists():
            continue
        output_dir = manifest_path.parent / "tables" / "latex"
        output_dir.mkdir(parents=True, exist_ok=True)
        doc = fitz.open(pdf_path)
        for asset in table_assets:
            label = asset.get("label", "Table")
            output_path = output_dir / f"{label}.tex"
            original = manifest_path.parent / asset.get("original", "")
            rows: list[list[str]] = []
            try:
                page = doc[int(asset.get("page", 0))]
                table = choose_table(page, asset.get("content_bbox"))
                if table is not None:
                    rows = normalize_rows(table.extract())
            except Exception:
                rows = []
            if len(rows) >= 1 and rows[0]:
                content = tabular_tex(asset.get("caption", ""), rows)
                mode = "extracted_tabular"
                extracted += 1
            else:
                relative_image = Path("..") / "original" / original.name
                content = image_wrapper_tex(asset.get("caption", ""), relative_image)
                mode = "image_wrapper"
                wrapped += 1
            output_path.write_text(content, encoding="utf-8")
            asset["latex"] = output_path.relative_to(manifest_path.parent).as_posix()
            asset["latex_mode"] = mode
        data.setdefault("notes", []).append("LaTeX tables generated by tools/build_latex_tables.py.")
        manifest_path.write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"latex_extracted={extracted} image_wrappers={wrapped}")


if __name__ == "__main__":
    main()
